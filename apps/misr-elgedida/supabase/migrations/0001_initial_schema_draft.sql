begin;

create extension if not exists pgcrypto;

create table public.branches (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  code text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('manager','branch_manager','reception','accountant')),
  branch_id uuid references public.branches(id),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  check ((role = 'manager' and branch_id is null) or (role <> 'manager' and branch_id is not null))
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  customer_no bigint generated by default as identity,
  full_name text not null,
  phone text,
  address text,
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles(id),
  unique(branch_id, customer_no)
);

create table public.cars (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  customer_id uuid not null references public.customers(id),
  make text not null,
  model text not null,
  model_year integer,
  plate_no text,
  vin text,
  odometer_km integer,
  created_at timestamptz not null default now(),
  check (model_year is null or model_year between 1900 and 2100),
  check (odometer_km is null or odometer_km >= 0)
);

create table public.employees (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  employee_no bigint generated by default as identity,
  full_name text not null,
  job_title text,
  phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(branch_id, employee_no)
);

create table public.service_catalog (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  name text not null,
  description text,
  price numeric(12,2) not null default 0 check (price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(branch_id, name)
);

create table public.work_orders (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  order_no bigint generated by default as identity,
  customer_id uuid not null references public.customers(id),
  car_id uuid not null references public.cars(id),
  customer_complaint text,
  technician_notes text,
  status text not null default 'new' check (status in ('new','inspection','in_progress','waiting_parts','ready','delivered','cancelled')),
  odometer_km integer,
  opened_at timestamptz not null default now(),
  delivered_at timestamptz,
  created_by uuid references public.profiles(id),
  unique(branch_id, order_no),
  check (odometer_km is null or odometer_km >= 0)
);

create table public.work_order_services (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  work_order_id uuid not null references public.work_orders(id) on delete cascade,
  service_id uuid references public.service_catalog(id),
  service_name text not null,
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  quantity numeric(12,2) not null default 1 check (quantity > 0),
  created_at timestamptz not null default now()
);

create table public.inventory_items (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  item_no bigint generated by default as identity,
  sku text,
  name text not null,
  category text not null check (category in ('spare_part','filter','oil')),
  subcategory text,
  unit text not null default 'قطعة',
  quantity numeric(12,3) not null default 0 check (quantity >= 0),
  purchase_price numeric(12,2) not null default 0 check (purchase_price >= 0),
  sale_price numeric(12,2) not null default 0 check (sale_price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(branch_id, item_no)
);

create table public.work_order_parts (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  work_order_id uuid not null references public.work_orders(id) on delete cascade,
  item_id uuid not null references public.inventory_items(id),
  item_name text not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  invoice_no bigint generated by default as identity,
  work_order_id uuid references public.work_orders(id),
  customer_id uuid not null references public.customers(id),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  status text not null default 'unpaid' check (status in ('unpaid','part_paid','paid','cancelled')),
  issued_at timestamptz not null default now(),
  created_by uuid references public.profiles(id),
  unique(branch_id, invoice_no)
);

create table public.invoice_items (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  item_type text not null check (item_type in ('service','inventory','labor','other')),
  description text not null,
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  line_total numeric(12,2) not null default 0 check (line_total >= 0)
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  invoice_id uuid not null references public.invoices(id),
  amount numeric(12,2) not null check (amount > 0),
  method text not null check (method in ('cash','instapay','wallet','visa','other')),
  reference text,
  paid_at timestamptz not null default now(),
  received_by uuid references public.profiles(id)
);

create table public.expenses (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  document_no bigint generated by default as identity,
  description text not null,
  amount numeric(12,2) not null check (amount > 0),
  category text,
  payment_method text,
  occurred_at timestamptz not null default now(),
  created_by uuid references public.profiles(id),
  unique(branch_id, document_no)
);

create table public.attendance (
  id uuid primary key default gen_random_uuid(),
  branch_id uuid not null references public.branches(id),
  record_no bigint generated by default as identity,
  employee_id uuid not null references public.employees(id),
  check_in timestamptz not null default now(),
  check_out timestamptz,
  notes text,
  created_by uuid references public.profiles(id),
  unique(branch_id, record_no),
  check (check_out is null or check_out >= check_in)
);

create table public.audit_logs (
  id bigint generated always as identity primary key,
  branch_id uuid references public.branches(id),
  actor_id uuid references public.profiles(id),
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.audit_logs_archive (
  id bigint primary key,
  branch_id uuid references public.branches(id),
  actor_id uuid references public.profiles(id),
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null,
  archived_at timestamptz not null default now()
);

-- Branch context: only the central manager (role=manager and branch_id NULL)
-- can access all branches. Other users are restricted to their assigned branch.
create or replace function public.current_profile_role()
returns text language sql stable security definer
set search_path = public, pg_temp
as $$
  select p.role from public.profiles p
  where p.id = auth.uid() and p.is_active = true
  limit 1
$$;

create or replace function public.can_access_branch(target_branch uuid)
returns boolean language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.is_active = true
      and (p.role = 'manager' and p.branch_id is null
           or p.branch_id = target_branch)
  )
$$;

create or replace function public.can_manage_branch(target_branch uuid)
returns boolean language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.is_active = true
      and (p.role = 'manager' and p.branch_id is null
           or (p.branch_id = target_branch and p.role in ('branch_manager','reception','accountant')))
  )
$$;

