create policy "branches_read_accessible" on public.branches for select to authenticated
using (public.can_access_branch(id));
create policy "branches_manager_update" on public.branches for update to authenticated
using (public.current_profile_role() = 'manager')
with check (public.current_profile_role() = 'manager');

create policy "profiles_read_self_or_manager" on public.profiles for select to authenticated
using (id = auth.uid() or public.current_profile_role() = 'manager'
       or (branch_id is not null and public.can_access_branch(branch_id)));
create policy "profiles_manager_write" on public.profiles for all to authenticated
using (public.current_profile_role() = 'manager')
with check (public.current_profile_role() = 'manager');

